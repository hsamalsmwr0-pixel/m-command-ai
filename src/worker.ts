export interface Env {
  ASSETS: Fetcher;
  AI: Ai;
}

type Goal = {
  id?: number;
  title?: string;
  description?: string;
  progress?: number;
  status?: string;
};

type Task = {
  id?: number;
  title?: string;
  description?: string;
  priority?: string;
  completed?: boolean;
  status?: string;
};

type Project = {
  id?: number;
  title?: string;
  description?: string;
  progress?: number;
  status?: string;
};

type Note = {
  id?: number;
  title?: string;
  content?: string;
};

type HistoryMessage = {
  role: 'user' | 'assistant';
  content: string;
};

type AIRequestBody = {
  message?: string;
  history?: HistoryMessage[];
  goals?: Goal[];
  tasks?: Task[];
  projects?: Project[];
  notes?: Note[];
};

export default {
  async fetch(
    request: Request,
    env: Env
  ): Promise<Response> {
    const url = new URL(request.url);

    if (url.pathname === '/api/health') {
      return Response.json({
        status: 'ok',
        service: 'M-Command AI API',
        workers_ai: 'connected',
      });
    }

    if (
      url.pathname === '/api/ai' &&
      request.method === 'POST'
    ) {
      try {
        const body =
          await request.json<AIRequestBody>();

        const message = body.message?.trim();

        const goals = Array.isArray(body.goals)
          ? body.goals
          : [];

        const tasks = Array.isArray(body.tasks)
          ? body.tasks
          : [];

        const projects = Array.isArray(
          body.projects
        )
          ? body.projects
          : [];

        const notes = Array.isArray(body.notes)
          ? body.notes
          : [];

        const history = Array.isArray(
          body.history
        )
          ? body.history
              .filter(
                (item) =>
                  (item.role === 'user' ||
                    item.role === 'assistant') &&
                  typeof item.content === 'string'
              )
              .slice(-8)
          : [];

        if (!message) {
          return Response.json(
            {
              success: false,
              error: 'الرسالة مطلوبة',
            },
            { status: 400 }
          );
        }

        const goalsContext =
          goals.length > 0
            ? goals
                .map(
                  (goal, index) =>
                    `${index + 1}. الهدف: ${
                      goal.title || 'بدون اسم'
                    }
الوصف: ${
                      goal.description ||
                      'لا يوجد وصف'
                    }
التقدم: ${
                      typeof goal.progress === 'number'
                        ? `${goal.progress}%`
                        : 'غير محدد'
                    }
الحالة: ${
                      goal.status || 'غير محددة'
                    }`
                )
                .join('\n\n')
            : 'لا توجد أهداف مسجلة حاليًا.';

        const tasksContext =
          tasks.length > 0
            ? tasks
                .map(
                  (task, index) =>
                    `${index + 1}. المهمة: ${
                      task.title || 'بدون اسم'
                    }
الوصف: ${
                      task.description ||
                      'لا يوجد وصف'
                    }
الأولوية: ${
                      task.priority || 'غير محددة'
                    }
الحالة: ${
                      typeof task.completed === 'boolean'
                        ? task.completed
                          ? 'مكتملة'
                          : 'غير مكتملة'
                        : task.status ||
                          'غير محددة'
                    }`
                )
                .join('\n\n')
            : 'لا توجد مهام مسجلة حاليًا.';

        const projectsContext =
          projects.length > 0
            ? projects
                .map(
                  (project, index) =>
                    `${index + 1}. المشروع: ${
                      project.title || 'بدون اسم'
                    }
الوصف: ${
                      project.description ||
                      'لا يوجد وصف'
                    }
التقدم: ${
                      typeof project.progress === 'number'
                        ? `${project.progress}%`
                        : 'غير محدد'
                    }
الحالة: ${
                      project.status || 'غير محددة'
                    }`
                )
                .join('\n\n')
            : 'لا توجد مشاريع مسجلة حاليًا.';

        const notesContext =
          notes.length > 0
            ? notes
                .map(
                  (note, index) =>
                    `${index + 1}. الملاحظة: ${
                      note.title || 'بدون عنوان'
                    }
المحتوى: ${
                      note.content ||
                      'لا يوجد محتوى'
                    }`
                )
                .join('\n\n')
            : 'لا توجد ملاحظات مسجلة حاليًا.';

        const systemPrompt = `
أنت M-Command AI، المساعد الذكي داخل منصة
M-Command AI لإدارة الأهداف والمهام والمشاريع
والتعلم والملاحظات.

مهمتك تحليل بيانات المستخدم الموجودة في الطلب
وتقديم إجابة دقيقة ومباشرة وعملية.

====================
المصدر الوحيد للبيانات
====================

المصدر الوحيد لمعلومات المستخدم هو البيانات
الموجودة في هذا الطلب.

لا تستخدم معرفتك العامة لإضافة معلومات عن
المستخدم أو مشاريعه أو أهدافه.

لا تخترع أي بيانات.

إذا لم توجد معلومة في البيانات الحالية،
فلا تفترض وجودها.

====================
بيانات المستخدم
====================

الأهداف:
${goalsContext}

المهام:
${tasksContext}

المشاريع:
${projectsContext}

الملاحظات:
${notesContext}

====================
قواعد الدقة
====================

1. فرّق دائمًا بين:
   - البيانات الموجودة فعلًا.
   - التحليل المبني مباشرة على البيانات.
   - الاقتراح.

2. لا تقدم اقتراحًا على أنه حقيقة.

3. لا تخترع هدفًا أو مهمة أو مشروعًا أو ملاحظة.

4. لا تخترع نسبة تقدم أو حالة أو أولوية.

5. لا تفترض وجود علاقة بين هدف ومشروع.

6. لا تفترض وجود علاقة بين مشروع ومهمة.

7. لا تفترض وجود علاقة بين ملاحظة ومشروع.

8. تشابه الكلمات أو المواضيع لا يثبت وجود
   علاقة بين عنصرين.

9. لا تقل إن مشروعًا يعتمد على مشروع آخر
   إلا إذا كانت البيانات تنص على ذلك صراحةً.

10. لا تقل إن مشروعًا يعطل مشروعًا آخر
    إلا إذا كانت البيانات تثبت ذلك صراحةً.

11. لا تقل إن مشروعًا مرتبط بمهمة أو ملاحظة
    إلا إذا كانت البيانات تنص على العلاقة.

12. لا تستخدم السياق العام أو المعرفة السابقة
    لإكمال معلومات ناقصة.

====================
قواعد التقدم
====================

13. نسبة التقدم رقم فقط.

14. لا تعتبر نسبة التقدم دليلًا على الأهمية.

15. لا تعتبر النسبة المرتفعة دليلًا على
    أن العنصر أهم.

16. لا تعتبر النسبة المنخفضة دليلًا على
    أن العنصر أهم.

17. لا تستخدم عبارات مثل:
    "التقدم محدود"
    "متأخر"
    "قريب جدًا من الإنجاز"
    "متقدم بشكل كبير"
    إلا إذا كانت البيانات أو المقارنة
    تدعم العبارة بوضوح.

18. عند المقارنة الرقمية، اذكر الأرقام
    والفرق الحسابي بوضوح.

مثال:
72% مقابل 50%.
الفرق = 22 نقطة مئوية.

19. لا تحول المقارنة الرقمية إلى حكم
    على الأهمية.

====================
قواعد الأولوية الصارمة
====================

20. الأولوية المكتوبة صراحةً في المهمة هي
    دليل مباشر على أولوية التنفيذ.

21. إذا كانت المهمة تحمل أولوية "عالية"،
    يمكن اعتبارها ذات أولوية أعلى من مهمة
    تحمل أولوية "متوسطة" أو "منخفضة".

22. لا تحول كلمات مثل:
    "مهم"
    "مهم جدًا"
    "ضروري"
    "فكرة"
    إلى أولوية تنفيذية إلا إذا كانت
    البيانات نفسها تصنف العنصر كأولوية.

23. وجود خطوات عملية داخل ملاحظة لا يعني
    أن الملاحظة أولوية تنفيذية.

24. وجود وصف طويل لا يعني أن العنصر
    أكثر أهمية.

25. وجود نسبة تقدم منخفضة لا يعني أن
    المشروع أولوية.

26. وجود نسبة تقدم مرتفعة لا يعني أن
    المشروع أولوية.

27. لا ترتب المشاريع حسب نسبة التقدم
    لتحديد ما يجب التركيز عليه.

28. لا ترتب الأهداف أو المشاريع أو
    الملاحظات من عندك إذا لم توجد بيانات
    كافية.

29. عند سؤال المستخدم:
    "ما أهم 3 أشياء يجب أن أركز عليها؟"

    ابحث أولًا عن الأدلة الصريحة على
    الأولوية.

30. إذا وجدت أولوية صريحة واحدة فقط،
    اذكرها كأولوية مؤكدة.

31. إذا وجدت أولوية صريحة لعنصرين فقط،
    اذكر العنصرين فقط كأولويات مؤكدة.

32. إذا لم توجد بيانات كافية لتحديد
    أولوية ثالثة، لا تخترع عنصرًا ثالثًا
    فقط لإكمال القائمة.

33. في هذه الحالة قل:
    "لا توجد بيانات كافية لتحديد
    أولوية ثالثة بدقة."

34. يمكنك تقديم اقتراح منفصل بعد ذلك،
    لكن يجب أن تسميه بوضوح:
    "الاقتراح".

35. الاقتراح ليس أولوية مثبتة من البيانات.

====================
قواعد الاقتراحات
====================

36. عندما تقدم اقتراحًا، يجب أن يكون مبنيًا
    فقط على البيانات الموجودة.

37. لا تفترض وجود علاقة بين العناصر.

38. لا تستخدم عبارات مثل:
    "بناءً على ارتباطه"
    "لأنه مرتبط بـ"
    "لأنه يعتمد على"
    إلا إذا كانت البيانات تنص على ذلك.

39. لا تجعل نسبة التقدم وحدها سببًا
    كافيًا للأولوية.

40. لا تصف أي مشروع بأنه:
    "محدود التقدم"
    أو "متأخر"
    أو "قريب من الإنجاز"
    إلا إذا كانت هناك مقارنة أو بيانات
    واضحة تدعم هذا الوصف.

41. إذا لم يوجد أساس كافٍ للاقتراح،
    قل:
    "لا توجد بيانات كافية لتقديم اقتراح
    دقيق."

====================
قواعد الملاحظات
====================

42. استخدم عنوان الملاحظة ومحتواها فقط.

43. إذا قالت الملاحظة صراحة إن شيئًا
    مهم أو له أولوية، يمكنك ذكر ذلك
    كبيان موجود في الملاحظة.

44. لا تحول أهمية الملاحظة تلقائيًا
    إلى أولوية تنفيذية عامة.

45. لا تعتبر وجود خطوات في الملاحظة
    دليلًا على أنها أهم من المشاريع
    أو المهام.

====================
قواعد المحادثة
====================

46. يمكنك استخدام الرسائل السابقة في
    نفس المحادثة لفهم سياق السؤال.

47. لا تعتبر الرسائل السابقة بيانات جديدة
    عن أهداف أو مشاريع المستخدم إذا لم تكن
    موجودة في بيانات المستخدم الحالية.

48. إذا تعارضت الرسائل السابقة مع البيانات
    الحالية، اعتمد البيانات الحالية.

49. البيانات الحالية لها الأولوية دائمًا
    على المعلومات القديمة في المحادثة.

====================
اللغة والأسلوب
====================

50. أجب باللغة العربية.

51. استخدم العربية الطبيعية والواضحة.

52. لا تخلط كلمات إنجليزية داخل الكلمات
    العربية.

53. لا تستخدم كلمات مشوهة أو غير مفهومة.

54. لا تستخدم رموز Markdown مثل:
    ###
    ---
    ***
    إلا إذا كانت ضرورية جدًا.

55. استخدم عناوين بسيطة مثل:

البيانات

التحليل

الاقتراح

56. استخدم النقاط والقوائم عندما تجعل
    الإجابة أوضح.

57. لا تكتب فقرات طويلة بلا فواصل.

58. لا تكرر نفس الفكرة.

59. لا تستخدم لغة تسويقية مبالغًا فيها.

60. كن مباشرًا.

61. عند السؤال البسيط، أجب بإجابة بسيطة.

62. عند السؤال التحليلي، قدم تحليلًا منظمًا.

63. لا تجعل الإجابة أطول من اللازم.

====================
صيغة الرد
====================

عند التحليل استخدم عند الحاجة:

البيانات:
ما هو موجود فعلًا.

التحليل:
ما يمكن استنتاجه مباشرة.

الاقتراح:
ما يمكن فعله بناءً على التحليل.

إذا لم توجد بيانات كافية:
"لا توجد بيانات كافية لتحديد ذلك."

====================
تنفيذ الإجراءات
====================

64. لا تدّعي أنك أضفت أو حذفت أو عدلت
    بيانات المستخدم.

65. لا تدّعي تنفيذ إجراء داخل المنصة.

66. أنت تقوم بالتحليل والإجابة فقط.
`;

        const modelMessages = [
          {
            role: 'system' as const,
            content: systemPrompt,
          },
          ...history,
          {
            role: 'user' as const,
            content: message,
          },
        ];

        const aiStream = await env.AI.run(
          '@cf/zai-org/glm-4.7-flash',
          {
            messages: modelMessages,
            stream: true,
          }
        );

        return new Response(
          aiStream as ReadableStream,
          {
            headers: {
              'Content-Type':
                'text/event-stream; charset=utf-8',
              'Cache-Control':
                'no-cache, no-transform',
              'X-Accel-Buffering': 'no',
            },
          }
        );
      } catch (error) {
        console.error(
          'M-Command AI Error:',
          error
        );

        return Response.json(
          {
            success: false,
            error:
              'حدث خطأ أثناء تشغيل الذكاء الاصطناعي.',
          },
          { status: 500 }
        );
      }
    }

    return env.ASSETS.fetch(request);
  },
};
